package Exercicios.ex_7_functions.ex4.exercicio3;

public class Main {
    static void cont(int Numero){
        
        for(int x=0; x<=10; x++){
                System.out.println(Numero + " x " + x + " = " + Numero*x);
            }
        System.out.println("\n");
    }
    public static void main(String[] args){
        cont(6);
    }
    
}
